#!/usr/bin/env bash
# Host side, run by the dev container's initializeCommand: writes .devcontainer/gpu.generated.yml, a compose
# override that hands the host GPU to the container. Never fails: without a usable GPU the file is a no-op
# and the container renders in software.
#   WSL2 GPU          /dev/dxg + /usr/lib/wsl         (any vendor, Mesa d3d12)
#   NVIDIA            nvidia container runtime         (needs nvidia-container-toolkit)
#   AMD / Intel / ... /dev/dri render nodes            (Mesa radeonsi / iris / anv / radv, Vulkan too)
set -u
cd "$(dirname "$0")"
OUT=gpu.generated.yml
env_lines=() dev_lines=() vol_lines=() group_lines=() mode=software nvidia=0

if [ -e /dev/dxg ]; then
    mode=wsl
    dev_lines+=("/dev/dxg:/dev/dxg")
    [ -d /usr/lib/wsl ] && vol_lines+=("/usr/lib/wsl:/usr/lib/wsl:ro")
elif command -v nvidia-smi >/dev/null 2>&1 && nvidia-smi -L >/dev/null 2>&1 \
        && docker info --format '{{json .Runtimes}}' 2>/dev/null | grep -q nvidia; then
    mode=nvidia nvidia=1
fi

if [ -d /dev/dri ] && compgen -G "/dev/dri/renderD*" >/dev/null; then
    [ "$mode" = software ] && mode=dri
    dev_lines+=("/dev/dri:/dev/dri")
    # Numeric gids: the group names inside the container differ from the host's.
    for node in /dev/dri/renderD* /dev/dri/card*; do
        [ -e "$node" ] && group_lines+=("$(stat -c %g "$node")")
    done
    mapfile -t group_lines < <(printf '%s\n' "${group_lines[@]}" | sort -u)
fi

{
    echo "# Generated by .devcontainer/detect_gpu.sh on every container start; do not edit."
    echo "services:"
    echo "  student:"
    echo "    environment:"
    echo "      BITT_HOST_GPU: \"$mode\""
    [ "$nvidia" = 1 ] && echo "      NVIDIA_DRIVER_CAPABILITIES: all" && echo "      NVIDIA_VISIBLE_DEVICES: all"
    [ "$mode" = wsl ] && echo "      LD_LIBRARY_PATH: /usr/lib/wsl/lib"
    if [ ${#dev_lines[@]} -gt 0 ]; then echo "    devices:"; printf '      - "%s"\n' "${dev_lines[@]}"; fi
    if [ ${#vol_lines[@]} -gt 0 ]; then echo "    volumes:"; printf '      - "%s"\n' "${vol_lines[@]}"; fi
    if [ ${#group_lines[@]} -gt 0 ]; then echo "    group_add:"; printf '      - "%s"\n' "${group_lines[@]}"; fi
    if [ "$nvidia" = 1 ]; then
        echo "    deploy:"
        echo "      resources:"
        echo "        reservations:"
        echo "          devices:"
        echo "            - driver: nvidia"
        echo "              count: all"
        echo "              capabilities: [gpu, graphics, compute, utility, display]"
    fi
} > "$OUT"

echo "GPU for the dev container: $mode"
